router = APIRouter(prefix='/explain', tags=['Execution transparency'])
RESOURCES = Path(__file__).parent / 'resources'
Configuration = Literal['baseline_q1', 'baseline_q2', 'q1', 'q2']


class ExperimentRequest(BaseModel):
    ticket_id: str = Field(pattern=r'^T-[0-9]{4}$', max_length=6)
    configurations: list[Configuration] = Field(min_length=1, max_length=4)
    model_config = {'extra': 'forbid'}


@lru_cache(maxsize=1)
def baseline_context() -> str:
    """Byte-identical output from the unchanged original KB generator.

    Only cold setup is precomputed. Every model call, prompt, response and cost
    is generated by the original baseline handle_ticket implementation live.
    """
    data = gzip.decompress((RESOURCES / 'baseline-help-center.txt.gz').read_bytes())
    manifest = json.loads((RESOURCES / 'baseline-manifest.json').read_text())
    if hashlib.sha256(data).hexdigest() != manifest['sha256']:
        raise RuntimeError('Baseline context integrity check failed')
    return data.decode()


def instrument(configuration: Configuration, ticket_id: str) -> dict:
    if ticket_id not in TICKET_EXPECTATIONS:
        raise HTTPException(404, 'Unknown sample ticket')
    start = perf_counter()
    if configuration == 'baseline_q2':
        # Constructor-equivalent hydration, retaining every original method.
        agent = OriginalQ2.__new__(OriginalQ2)
        agent.session = CostSession()
        agent.llm = LlmClient(agent.session)
        agent.help_center = baseline_context()
    else:
        agent = {'baseline_q1': OriginalQ1, 'q1': SupportCopilot,
                 'q2': SupportPipeline}[configuration]()
    setup_ms = (perf_counter() - start) * 1000
    captured = []
    original_chat = agent.llm.chat

    def observed_chat(label, messages, **kwargs):
        call_start = perf_counter()
        completion = original_chat(label, messages, **kwargs)
        captured.append({
            **call_metrics(agent.session.calls[-1]),
            'prompt': agent.session.calls[-1].prompt,
            'completion': completion,
            'messages': [{'role': m.role, 'content': m.content} for m in messages],
            'duration_ms': round((perf_counter() - call_start) * 1000, 3),
        })
        return completion

    agent.llm.chat = observed_chat
    execute_start = perf_counter()
    resolution = agent.handle_ticket(ticket_id)
    duration_ms = (perf_counter() - execute_start) * 1000
    expected = TICKET_EXPECTATIONS[ticket_id]
    parsed = parse_resolution(agent.session.calls[-1].completion)
    ticket = get_ticket(ticket_id)
    order = get_order(ticket['order_id'])
    stages = []
    for stage in getattr(agent, 'stages', []):
        name = stage['name']
        inputs = {
            'triage': {'thread': format_thread(ticket), 'order': order},
            'retrieve': {'order': order, 'thread': format_thread(ticket)},
            'compose': {'prompt': captured[0]['prompt']},
            'audit': {'completion': captured[-1]['completion'],
                      'candidate_articles': next((s['result'].get('articles', []) for s in agent.stages if s['name'] == 'retrieve'), [])},
        }
        stages.append({**stage, 'input': inputs[name], 'output': stage['result'],
                       'model_calls': 1 if stage['kind'] == 'llm' else 0})
    return {
        'configuration': configuration, 'ticket_id': ticket_id,
        'action': resolution.action, 'kb_article': resolution.kb_article,
        'customer_reply': parsed.customer_reply,
        'correct': (resolution.action, resolution.kb_article) == (expected.action, expected.kb_article),
        'points': agent.session.total_points(), 'calls': captured, 'stages': stages,
        'input_tokens': sum(c['input_tokens'] for c in captured),
        'output_tokens': sum(c['output_tokens'] for c in captured),
        'cached_input_tokens': sum(c['cached_input_tokens'] for c in captured),
        'model_calls': len(captured), 'duration_ms': round(duration_ms, 3),
        'setup_ms': round(setup_ms, 3),
        'engine': 'Provided local LLM simulator', 'configured_model': agent.llm.model,
        'provider': 'Local Python; no hosted provider',
        'setup_note': 'Q2 baseline context hydrated from verified original generator output; cold generation excluded from execution time.' if configuration == 'baseline_q2' else 'Normal agent construction; setup time shown separately.',
    }


@router.post('/experiments')
def experiments(body: ExperimentRequest):
    configurations = list(dict.fromkeys(body.configurations))
    return {'ticket_id': body.ticket_id,
            'executions': [instrument(c, body.ticket_id) for c in configurations],
            'measurement': 'Fresh sessions. Real model-simulator calls. No estimated costs.'}


